import java.time.Clock;
import java.time.LocalDate;
import java.time.LocalTime;
import java.util.List;

/**
 * Booking rules. Double booking is prevented in three layers:
 * <ol>
 *   <li>the dentist row is locked ({@code SELECT ... FOR UPDATE}) so bookings of one dentist are serialised;</li>
 *   <li>the new interval is compared with the dentist's existing intervals (catches overlaps);</li>
 *   <li>{@code UNIQUE(dentist_id, appointment_date, appointment_time)} is the final database guarantee.</li>
 * </ol>
 * The appointment number is generated by the database trigger; listeners are notified after the commit.
 */
public final class AppointmentService {

    private final TransactionManager transactions;
    private final PatientDao patientDao;
    private final DentistDao dentistDao;
    private final TreatmentDao treatmentDao;
    private final AppointmentDao appointmentDao;
    private final BillDao billDao;
    private final AuditDao auditDao;
    private final EventPublisher publisher;
    private final Clock clock;

    /**
     * Creates the service.
     *
     * @param transactions   connection handling
     * @param patientDao     patient access
     * @param dentistDao     dentist access
     * @param treatmentDao   treatment access
     * @param appointmentDao appointment access
     * @param billDao        bill access (cancelling voids an unpaid bill)
     * @param auditDao       sets the audit identity of the transaction
     * @param publisher      event bus
     * @param clock          source of "today"
     */
    public AppointmentService(TransactionManager transactions, PatientDao patientDao, DentistDao dentistDao,
                              TreatmentDao treatmentDao, AppointmentDao appointmentDao, BillDao billDao,
                              AuditDao auditDao, EventPublisher publisher, Clock clock) {
        this.transactions = transactions;
        this.patientDao = patientDao;
        this.dentistDao = dentistDao;
        this.treatmentDao = treatmentDao;
        this.appointmentDao = appointmentDao;
        this.billDao = billDao;
        this.auditDao = auditDao;
        this.publisher = publisher;
        this.clock = clock;
    }

    /**
     * Books an appointment.
     *
     * @param request what to book
     * @param actor   the logged-in staff member
     * @return the stored appointment including its generated number
     * @throws ValidationException on invalid input or if the slot is outside the dentist's working hours
     * @throws NotFoundException   if the patient, dentist or treatment does not exist
     * @throws ConflictException   if the dentist is not free
     */
    public Appointment book(BookAppointmentRequest request, User actor) {
        Validator.requireNonNull(request, "request");
        Validator.requireNonNull(actor, "actor");
        Appointment candidate = new AppointmentBuilder(clock)
                .patientId(request.patientId())
                .dentistId(request.dentistId())
                .treatmentId(request.treatmentId())
                .date(request.date())
                .time(request.time())
                .notes(request.notes())
                .createdBy(Validator.requireId(actor.getId(), "actor"))
                .build();

        BookingResult booked = transactions.inTransaction(c -> reserve(c, candidate, actor));

        Patient patient = booked.patient();
        publisher.publish(new AppointmentCreatedEvent(booked.appointment().getId(),
                booked.appointment().getAppointmentNumber(), patient.getId(), patient.getFullName(),
                patient.getEmail(), booked.dentist().getFullName(), booked.treatment().getName(),
                candidate.getAppointmentDate(), candidate.getAppointmentTime(), actor.getUsername()));
        return booked.appointment();
    }

    /**
     * Cancels an appointment; an unpaid bill is voided, a paid bill blocks the cancellation.
     *
     * @param appointmentId appointment id
     * @param actor         the logged-in staff member
     * @return the updated appointment
     */
    public Appointment cancel(long appointmentId, User actor) {
        return updateStatus(appointmentId, AppointmentStatus.CANCELLED, actor);
    }

    /**
     * Moves an appointment to a new status if the lifecycle allows it.
     *
     * @param appointmentId appointment id
     * @param next          the new status
     * @param actor         the logged-in staff member
     * @return the updated appointment
     * @throws ConflictException if the transition is not allowed
     */
    public Appointment updateStatus(long appointmentId, AppointmentStatus next, User actor) {
        Validator.requireId(appointmentId, "appointmentId");
        Validator.requireNonNull(next, "status");
        Validator.requireNonNull(actor, "actor");
        return transactions.inTransaction(c -> {
            Appointment current = appointmentDao.findByIdForUpdate(c, appointmentId)
                    .orElseThrow(() -> new NotFoundException("Appointment", appointmentId));
            if (!current.getStatus().canTransitionTo(next)) {
                throw new ConflictException("An appointment that is " + current.getStatus()
                        + " cannot become " + next);
            }
            if (next == AppointmentStatus.CANCELLED) {
                releaseBill(c, appointmentId);
            }
            auditDao.setApplicationUser(c, actor.getUsername());
            appointmentDao.updateStatus(c, appointmentId, next);
            return appointmentDao.findById(c, appointmentId)
                    .orElseThrow(() -> new NotFoundException("Appointment", appointmentId));
        });
    }

    /**
     * Loads an appointment.
     *
     * @param id appointment id
     * @return the appointment
     */
    public Appointment get(long id) {
        Validator.requireId(id, "appointmentId");
        return transactions.read(c -> appointmentDao.findById(c, id))
                .orElseThrow(() -> new NotFoundException("Appointment", id));
    }

    /**
     * Loads an appointment by its public number.
     *
     * @param number appointment number such as APT-0001
     * @return the appointment
     * @throws NotFoundException if absent
     */
    public Appointment getByNumber(String number) {
        String clean = Validator.requireText(number, "appointmentNumber", 12);
        return transactions.read(c -> appointmentDao.findByNumber(c, clean))
                .orElseThrow(() -> new NotFoundException("Appointment", clean));
    }

    /**
     * Lists the appointments of a day.
     *
     * @param date the day
     * @return appointments ordered by time
     */
    public List<Appointment> findByDate(LocalDate date) {
        return findByDate(date, null);
    }

    /**
     * Lists the appointments of a day, optionally of one dentist.
     *
     * @param date      the day
     * @param dentistId dentist filter, {@code null} for all dentists
     * @return appointments ordered by time
     */
    public List<Appointment> findByDate(LocalDate date, Long dentistId) {
        Validator.requireNonNull(date, "date");
        List<Appointment> all = transactions.read(c -> appointmentDao.findByDate(c, date));
        if (dentistId == null) {
            return all;
        }
        return all.stream().filter(a -> dentistId.equals(a.getDentistId())).toList();
    }

    /**
     * Moves a scheduled or confirmed appointment to a new day and time, re-checking working hours and
     * overlaps under the same dentist lock that booking uses.
     *
     * @param appointmentId appointment id
     * @param date          new day
     * @param time          new start time (15-minute boundary)
     * @param notes         new notes; {@code null} keeps the existing notes
     * @param actor         the logged-in staff member
     * @return the updated appointment
     * @throws ConflictException if the status does not allow it or the dentist is not free
     */
    public Appointment reschedule(long appointmentId, LocalDate date, LocalTime time, String notes, User actor) {
        Validator.requireId(appointmentId, "appointmentId");
        Validator.requireNonNull(actor, "actor");
        AppointmentBuilder.validateSchedule(date, time, clock);
        String cleanNotes = Validator.optionalText(notes, "notes", 500);
        return transactions.inTransaction(c -> {
            Appointment peek = appointmentDao.findById(c, appointmentId)
                    .orElseThrow(() -> new NotFoundException("Appointment", appointmentId));
            long dentistId = peek.getDentistId();
            Dentist dentist = dentistDao.findByIdForUpdate(c, dentistId)
                    .orElseThrow(() -> new NotFoundException("Dentist", dentistId));
            Appointment current = appointmentDao.findByIdForUpdate(c, appointmentId)
                    .orElseThrow(() -> new NotFoundException("Appointment", appointmentId));
            if (current.getStatus() != AppointmentStatus.SCHEDULED
                    && current.getStatus() != AppointmentStatus.CONFIRMED) {
                throw new ConflictException("Only scheduled or confirmed appointments can be rescheduled");
            }
            Treatment treatment = treatmentDao.findById(c, current.getTreatmentId())
                    .orElseThrow(() -> new NotFoundException("Treatment", current.getTreatmentId()));
            ensureWithinWorkingHours(dentist, time, treatment.getDurationMinutes());
            ensureNoOverlap(appointmentDao.findActiveSlots(c, dentistId, date, appointmentId),
                    time, treatment.getDurationMinutes());
            auditDao.setApplicationUser(c, actor.getUsername());
            try {
                appointmentDao.reschedule(c, appointmentId, date, time,
                        cleanNotes != null ? cleanNotes : current.getNotes());
            } catch (DataAccessException e) {
                if (e.isDuplicateKey()) {
                    throw new ConflictException("That start time is not available for this dentist");
                }
                if (e.isBusinessRuleViolation()) {
                    throw new ValidationException(e.getSqlMessage());
                }
                throw e;
            }
            return appointmentDao.findById(c, appointmentId)
                    .orElseThrow(() -> new NotFoundException("Appointment", appointmentId));
        });
    }

    /**
     * Lists the appointments of a patient, newest first.
     *
     * @param patientId patient id
     * @return appointments
     */
    public List<Appointment> findByPatient(long patientId) {
        Validator.requireId(patientId, "patientId");
        return transactions.read(c -> appointmentDao.findByPatient(c, patientId));
    }

    /** @return the dentists that accept appointments */
    public List<Dentist> listDentists() {
        return transactions.read(dentistDao::findAllActive);
    }

    /** @return the treatments that can be booked */
    public List<Treatment> listTreatments() {
        return transactions.read(treatmentDao::findAllActive);
    }

    private BookingResult reserve(Connection c, Appointment candidate, User actor) {
        long dentistId = candidate.getDentistId();
        // Lock first: every concurrent booking of this dentist waits here until we commit or roll back.
        Dentist dentist = dentistDao.findByIdForUpdate(c, dentistId)
                .orElseThrow(() -> new NotFoundException("Dentist", dentistId));
        if (!dentist.isActive()) {
            throw new ValidationException("The dentist does not accept appointments");
        }
        Patient patient = patientDao.findById(c, candidate.getPatientId())
                .orElseThrow(() -> new NotFoundException("Patient", candidate.getPatientId()));
        Treatment treatment = treatmentDao.findById(c, candidate.getTreatmentId())
                .orElseThrow(() -> new NotFoundException("Treatment", candidate.getTreatmentId()));
        if (!treatment.isActive()) {
            throw new ValidationException("The treatment is not offered any more");
        }

        LocalTime start = candidate.getAppointmentTime();
        ensureWithinWorkingHours(dentist, start, treatment.getDurationMinutes());
        ensureNoOverlap(appointmentDao.findActiveSlots(c, dentistId, candidate.getAppointmentDate(), 0L),
                start, treatment.getDurationMinutes());

        auditDao.setApplicationUser(c, actor.getUsername());
        try {
            Appointment saved = appointmentDao.insert(c, candidate);
            return new BookingResult(saved, patient, dentist, treatment);
        } catch (DataAccessException e) {
            if (e.isDuplicateKey()) {
                throw new ConflictException("That start time is not available for this dentist");
            }
            if (e.isBusinessRuleViolation()) {
                throw new ValidationException(e.getSqlMessage());
            }
            throw e;
        }
    }

    private void releaseBill(Connection c, long appointmentId) {
        billDao.findByAppointmentId(c, appointmentId).ifPresent(bill -> {
            if (bill.getPaymentStatus() == PaymentStatus.PAID) {
                throw new ConflictException("The appointment has a paid bill; refund it before cancelling");
            }
            if (bill.getPaymentStatus() == PaymentStatus.UNPAID) {
                billDao.voidBill(c, bill.getId());
            }
        });
    }

    /**
     * Rejects intervals that start before the dentist's shift or end after it.
     *
     * @param dentist         the dentist
     * @param start           start of the treatment
     * @param durationMinutes length of the treatment
     */
    static void ensureWithinWorkingHours(Dentist dentist, LocalTime start, int durationMinutes) {
        int startMinute = start.toSecondOfDay() / 60;
        int endMinute = startMinute + durationMinutes;
        int shiftStart = dentist.getWorkStart().toSecondOfDay() / 60;
        int shiftEnd = dentist.getWorkEnd().toSecondOfDay() / 60;
        if (startMinute < shiftStart || endMinute > shiftEnd) {
            throw new ValidationException(String.format(
                    "%s works %s-%s; a %d-minute treatment at %s does not fit", dentist.getFullName(),
                    dentist.getWorkStart(), dentist.getWorkEnd(), durationMinutes, start));
        }
    }

    /**
     * Rejects an interval that overlaps an existing booking. Back-to-back bookings are fine.
     *
     * @param booked          the dentist's existing busy intervals of the day
     * @param start           start of the new treatment
     * @param durationMinutes length of the new treatment
     */
    static void ensureNoOverlap(List<BookedSlot> booked, LocalTime start, int durationMinutes) {
        for (BookedSlot slot : booked) {
            if (slot.overlaps(start, durationMinutes)) {
                throw new ConflictException("The dentist is already booked from " + slot.start()
                        + " to " + slot.end() + " on that day");
            }
        }
    }

    private record BookingResult(Appointment appointment, Patient patient, Dentist dentist, Treatment treatment) {
    }
}
