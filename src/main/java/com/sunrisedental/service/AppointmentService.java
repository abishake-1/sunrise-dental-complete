import com.sunrisedental.dao.DentistDao;
import com.sunrisedental.dao.PatientDao;
import com.sunrisedental.dao.TransactionManager;
import com.sunrisedental.dao.TreatmentDao;
import com.sunrisedental.dto.BookAppointmentRequest;
import com.sunrisedental.model.Appointment;
import com.sunrisedental.model.AppointmentStatus;
import com.sunrisedental.model.BookedSlot;
import com.sunrisedental.model.Dentist;
import com.sunrisedental.model.Patient;
import com.sunrisedental.model.PaymentStatus;
import com.sunrisedental.model.Treatment;
import com.sunrisedental.model.User;
import com.sunrisedental.pattern.AppointmentBuilder;
import com.sunrisedental.pattern.AppointmentCreatedEvent;
import com.sunrisedental.pattern.EventPublisher;
import com.sunrisedental.util.ConflictException;
import com.sunrisedental.util.NotFoundException;
import com.sunrisedental.util.ValidationException;
